# 二进制 以Ob开头
binary_number = 0b1010

# 八进制 以0o开头
octal_number = 0o12

# 十六禁止 以0x开头
hex_number = 0xA

print(binary_number, octal_number, hex_number) # 10 10 10
print(bin(binary_number), oct(octal_number), hex(hex_number)) # 0b1010 0o12 0xa


